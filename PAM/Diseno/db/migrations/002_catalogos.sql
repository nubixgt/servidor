CREATE TABLE ref.departamento(
  id smallint PRIMARY KEY,
  codigo char(2) NOT NULL UNIQUE,
  nombre text NOT NULL
);
-- id = código INE numérico del municipio (p. ej. 1601 = Cobán); id/100 = departamento.
CREATE TABLE ref.municipio(
  id smallint PRIMARY KEY,
  codigo char(4) NOT NULL UNIQUE,
  departamento_id smallint NOT NULL REFERENCES ref.departamento(id),
  nombre text NOT NULL
);
CREATE INDEX ON ref.municipio(departamento_id);

CREATE TABLE ref.cat_estado(
  id smallint PRIMARY KEY,
